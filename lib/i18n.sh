#!/usr/bin/env bash
# Shared string catalogue for the copilot-key shell scripts.
#
# English is the source language; any key a translation omits falls back to it.
# Language comes from $COPILOT_KEY_LANG, else $LC_ALL / $LC_MESSAGES / $LANG.
# To add a language: add a T_<CODE> array and one case branch in copilot_lang.
#
# Usage:  source lib/i18n.sh
#         echo "$(t key)"           plain string
#         echo "$(t key "$value")"  string with %s placeholders

copilot_lang() {
    local raw="${COPILOT_KEY_LANG:-${LC_ALL:-${LC_MESSAGES:-${LANG:-}}}}"
    case "${raw%%[._]*}" in
        de|de-*) echo de ;;
        *) echo en ;;
    esac
}
COPILOT_LANG="$(copilot_lang)"


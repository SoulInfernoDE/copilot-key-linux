t() {
    local key="$1"
    shift
    local fmt=""
    if [ "$COPILOT_LANG" = "de" ]; then fmt="${T_DE[$key]-}"; fi
    [ -n "$fmt" ] || fmt="${T_EN[$key]-$key}"
    if [ "$#" -gt 0 ]; then
        # shellcheck disable=SC2059  # the format string is ours, from the catalogue
        printf "$fmt" "$@"
    else
        printf '%s' "$fmt"
    fi
}
